use crate::mutator::Mutator;

pub struct Add_Async_To_Functions_18;

impl Mutator for Add_Async_To_Functions_18 {
    fn name(&self) -> &str {
        "Add_Async_To_Functions_18"
    }
    fn mutate(&self, file: &mut syn::File) {
        for item in &mut file.items {
            if let syn::Item::Fn(func) = item {
                if func.sig.asyncness.is_none() && func.sig.ident != "main" {
                    func.sig.asyncness = Some(token::Async {
                        span: Span::call_site(),
                    });
                }
            }
        }
    }
    fn chain_of_thought(&self) -> &str {
        ""
    }
}